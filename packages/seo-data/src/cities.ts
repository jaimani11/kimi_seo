/**
 * Allowlist of cities for programmatic SEO pages.
 *
 * Every entry here unlocks a fan of routes:
 *
 *   /{slug}-3-day-itinerary    (and 2, 4, 5, 7)
 *   /things-to-do-in-{slug}
 *
 * The allowlist gates this — without it, anyone could request
 * `/blahblah-9-day-itinerary` and we'd 200 a thin page with no
 * inventory, which is the textbook way to get a manual spam penalty
 * from Google.
 *
 * Slugs are lowercase kebab-case and stable. Names are display-form.
 * Country names are spelled out (used in headlines + JSON-LD).
 *
 * Add cities here as we get content / inventory coverage. Each line
 * unlocks 6 indexable URLs.
 */

export interface SeoCity {
  /** URL slug. Lowercase, hyphenated, ASCII-safe. */
  slug: string;
  /** Display name ("Tokyo"). */
  name: string;
  /** Free-text country name ("Japan"). */
  countryName: string;
  /** ISO-3166-1 alpha-2. */
  countryCode: string;
  /** Continent or sub-region tag — used to cluster the SEO footer. */
  region: 'asia' | 'europe' | 'americas' | 'mena' | 'oceania' | 'africa';
  /** Approximate centroid. Used for schema.org GeoCoordinates. */
  coordinates: { lat: number; lng: number };
  /**
   * One-line editorial pitch used in the hero + OG description. ≤140
   * chars, no banned voice words.
   */
  oneLiner: string;
  /**
   * Viator-aligned query that returns the best inventory volume for
   * this city. Usually just the city name; some cities work better
   * with country or region appended.
   */
  viatorQuery: string;
}

