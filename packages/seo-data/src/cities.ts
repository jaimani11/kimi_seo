/** Allowed itinerary durations (days). */
export const SEO_ITINERARY_DAYS: readonly number[] = [2, 3, 4, 5, 7];

/** Lookup helpers. */
export function findCityBySlug(slug: string): SeoCity | null {
  return SEO_CITIES.find((c) => c.slug === slug) ?? null;
}

export function isValidItineraryDays(n: number): boolean {
  return SEO_ITINERARY_DAYS.includes(n);
}

/** Group cities by region — used by the SEO link footer. */
export function citiesByRegion(): Record<SeoCity['region'], SeoCity[]> {
  const out: Record<SeoCity['region'], SeoCity[]> = {
    asia: [],
    europe: [],
    americas: [],
    mena: [],
    oceania: [],
    africa: [],
  };
  for (const c of SEO_CITIES) {
    out[c.region].push(c);
  }
  return out;
}
